/**
 * FreeRTOS stacks & watchdog — measure a task's stack; let the watchdog catch a stuck task.
 *
 * Pure ESP-IDF (uxTaskGetStackHighWaterMark, esp_task_wdt_add, esp_task_wdt_reset, the
 * task watchdog's menuconfig options; GPIO as Basic GPIO taught). Every log line is real
 * output from QEMU (./freertos-stacks-watchdog/lab).
 *
 *   1 problem   2048 everywhere: too small crashes, too big wastes → measure
 *   2 mark      the highest the stack gets → the high water mark
 *   3 measure   uxTaskGetStackHighWaterMark(NULL): the least free stack ever, in bytes
 *   4 demo      1556, then 1124 for good
 *   5 size      924 used → 1536 leaves 612
 *   6 trap      sized from the first reading (768) → that log line overflows
 *   7 stuck     a jammed button: stuck, but the idle watchdog can't see it
 *   8 watch     esp_task_wdt_add(NULL) + esp_task_wdt_reset()
 *   9 caught    5 s later: "- button (CPU 0/1)"
 *  10 config    timeout · Invoke panic handler
 *  11 mistake   a 10 s wait trips a 5 s watchdog · check in from the main loop
 *  12 payoff    "That's stacks and the watchdog."
 *
 * Everything — picture AND soundtrack — is driven by ./freertos-stacks-watchdog/timeline.ts.
 */
import React from 'react';
import { Audio, Sequence, staticFile } from 'remotion';
import { Caught } from './freertos-stacks-watchdog/Caught';
import { Config } from './freertos-stacks-watchdog/Config';
import { Demo } from './freertos-stacks-watchdog/Demo';
import { Mark } from './freertos-stacks-watchdog/Mark';
import { Measure } from './freertos-stacks-watchdog/Measure';
import { Mistake } from './freertos-stacks-watchdog/Mistake';
import { Payoff } from './freertos-stacks-watchdog/Payoff';
import { Problem } from './freertos-stacks-watchdog/Problem';
import { Size } from './freertos-stacks-watchdog/Size';
import { Stuck } from './freertos-stacks-watchdog/Stuck';
import { Trap } from './freertos-stacks-watchdog/Trap';
import { Watch } from './freertos-stacks-watchdog/Watch';
import { FPS, sceneDur, SCENES, SceneId, sceneStart, STACKS_FRAMES } from './freertos-stacks-watchdog/timeline';

export { STACKS_FRAMES };

const SCENE_COMPONENTS: Record<SceneId, React.FC> = {
  problem: Problem,
  mark: Mark,
  measure: Measure,
  demo: Demo,
  size: Size,
  trap: Trap,
  stuck: Stuck,
  watch: Watch,
  caught: Caught,
  config: Config,
  mistake: Mistake,
  payoff: Payoff,
};

export const FreeRTOSStacksWatchdog: React.FC = () => (
  <>
    {/* generated by scripts/freertos-stacks-watchdog-audio.ts from the same timeline */}
    <Audio src={staticFile('freertos-stacks-watchdog/mix.wav')} />
    {SCENES.map(({ id }) => {
      const C = SCENE_COMPONENTS[id];
      return (
        <Sequence key={id} from={Math.round(sceneStart(id) * FPS)} durationInFrames={Math.round(sceneDur(id) * FPS)} name={id}>
          <C />
        </Sequence>
      );
    })}
  </>
);
