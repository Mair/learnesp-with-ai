/**
 * FreeRTOS delay-until — wait until the next beat, not for a while.
 *
 * Pure ESP-IDF (xTaskGetTickCount, xTaskDelayUntil, vTaskDelay, ESP_LOGW; GPIO output only).
 *
 *   1 problem   two tasks, the same but the wait; LED A drifts
 *   2 why       30 + 200 = 230 ms per loop
 *   3 answer    wait until the next beat → UNTIL
 *   4 tick      xTaskGetTickCount: last = the first beat, once, before the loop
 *   5 until     xTaskDelayUntil(&last, 20 ticks): next = last + 20; whole ticks; old name
 *   6 demo      10 s: B 50 switches, A 44
 *   7 late      a 500 ms loop: no wait, catches up, back on the beat; pdFALSE → ESP_LOGW
 *   8 trap      last read inside the loop → drift again
 *   9 payoff    "That's delay until."
 *
 * Everything — picture AND soundtrack — is driven by ./freertos-delay-until/timeline.ts.
 */
import React from 'react';
import { Audio, Sequence, staticFile } from 'remotion';
import { Answer } from './freertos-delay-until/Answer';
import { Demo } from './freertos-delay-until/Demo';
import { Late } from './freertos-delay-until/Late';
import { Payoff } from './freertos-delay-until/Payoff';
import { Problem } from './freertos-delay-until/Problem';
import { Tick } from './freertos-delay-until/Tick';
import { Trap } from './freertos-delay-until/Trap';
import { Until } from './freertos-delay-until/Until';
import { Why } from './freertos-delay-until/Why';
import { FPS, sceneDur, SCENES, SceneId, sceneStart, UNTIL_FRAMES } from './freertos-delay-until/timeline';

export { UNTIL_FRAMES };

const frames = (id: SceneId) => Math.round(sceneDur(id) * FPS);

const SCENE_COMPONENTS: Record<SceneId, React.FC> = {
  problem: Problem,
  why: Why,
  answer: Answer,
  tick: Tick,
  until: Until,
  demo: Demo,
  late: Late,
  trap: Trap,
  payoff: Payoff,
};

export const FreeRTOSDelayUntil: React.FC = () => (
  <>
    {/* generated by scripts/freertos-delay-until-audio.ts from the same timeline */}
    <Audio src={staticFile('freertos-delay-until/mix.wav')} />
    {SCENES.map(({ id }) => {
      const C = SCENE_COMPONENTS[id];
      return (
        <Sequence key={id} from={Math.round(sceneStart(id) * FPS)} durationInFrames={frames(id)} name={id}>
          <C />
        </Sequence>
      );
    })}
  </>
);
