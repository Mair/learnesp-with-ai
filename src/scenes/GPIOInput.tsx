/**
 * GPIO input — reading a button.
 *
 * Pure ESP-IDF (app_main, driver/gpio.h, vTaskDelay) — no Arduino.
 *
 *   1 problem    a button to GND reads 0 when pressed — and floats when released
 *   2 answer     a weak resistor to 3.3 V holds it high → PULL-UP
 *   3 circuit    WROOM pin 30 (IO18) → button → GND; why GPIO 18; the input thresholds
 *   4 reset      gpio_reset_pin: known state — but input OFF → reads 0
 *   5 direction  gpio_set_direction(…, GPIO_MODE_INPUT): input buffer on; forget it → "pressed" forever
 *   6 pull       gpio_set_pull_mode(…, GPIO_PULLUP_ONLY): 4 modes, 45 kΩ / 73 µA, GPIO 34 returns ESP_OK anyway
 *   7 read       gpio_get_level: int not esp_err_t, a snapshot, == 0 means pressed
 *   8 demo       button → LED, read once a tick, real time
 *   9 count      level vs edge; bounce (Ganssle); the 10 ms poll debounces
 *  10 pulls      knob 2: pull-up vs pull-down; never both (1.65 V)
 *  11 payoff     "Make it an input. Give it a pull. Read its level."
 *
 * Everything — picture AND soundtrack — is driven by ./gpio-input/timeline.ts.
 * Edit that, then `npm run gpio-input`.
 */
import React from 'react';
import { Audio, Sequence, staticFile } from 'remotion';
import { Answer } from './gpio-input/Answer';
import { Circuit } from './gpio-input/Circuit';
import { Count } from './gpio-input/Count';
import { Demo } from './gpio-input/Demo';
import { Direction } from './gpio-input/Direction';
import { Payoff } from './gpio-input/Payoff';
import { Problem } from './gpio-input/Problem';
import { Pull } from './gpio-input/Pull';
import { Pulls } from './gpio-input/Pulls';
import { Read } from './gpio-input/Read';
import { Reset } from './gpio-input/Reset';
import { FPS, INPUT_FRAMES, sceneDur, SCENES, SceneId, sceneStart } from './gpio-input/timeline';

export { INPUT_FRAMES };

const frames = (id: SceneId) => Math.round(sceneDur(id) * FPS);

const SCENE_COMPONENTS: Record<SceneId, React.FC> = {
  problem: Problem,
  answer: Answer,
  circuit: Circuit,
  reset: Reset,
  direction: Direction,
  pull: Pull,
  read: Read,
  demo: Demo,
  count: Count,
  pulls: Pulls,
  payoff: Payoff,
};

export const GPIOInput: React.FC = () => (
  <>
    {/* generated by scripts/gpio-input-audio.ts from the same timeline */}
    <Audio src={staticFile('gpio-input/mix.wav')} />
    {SCENES.map(({ id }) => {
      const C = SCENE_COMPONENTS[id];
      return (
        <Sequence key={id} from={Math.round(sceneStart(id) * FPS)} durationInFrames={frames(id)} name={id}>
          <C />
        </Sequence>
      );
    })}
  </>
);
