/**
 * GPIO interrupts — let the pin tell you.
 *
 * Pure ESP-IDF (gpio_config, gpio_install_isr_service, gpio_isr_handler_add,
 * FreeRTOS queue + FromISR) — no Arduino.
 *
 *   1 problem    polling: 360 000 reads an hour; a short pulse slips between reads
 *   2 answer     the hardware watches the edge, interrupts the CPU → INTERRUPT
 *   3 config     gpio_config: 64-bit mask, mode, pulls, intr_type = NEGEDGE, errors
 *   4 service    gpio_install_isr_service(0): one CPU interrupt, the driver dispatches; flags; once
 *   5 handler    gpio_isr_handler_add: pin, function, argument; enables the pin; order
 *   6 isr        interrupt context: no blocking / logging, 1536-byte stack, FromISR, yield, IRAM_ATTR
 *   7 queue      xQueueCreate(10, 4 B); xQueueReceive(portMAX_DELAY) → suspended list
 *   8 demo       one press end to end; 100 wake-ups/s vs one per press
 *   9 bounce     5 edges → 5 interrupts; fix: wait 30 ms, xQueueReset, read once
 *  10 types      knob 2: NEG / POS / ANY edge; levels repeat → wake-up only
 *  11 the IDF    GPIO_PIN18_REG → GPIO_STATUS bit 18 → gpio_intr_service → fn(args)
 *  12 payoff     "Don't keep asking. Let the pin tell you."
 *
 * Everything — picture AND soundtrack — is driven by ./gpio-interrupts/timeline.ts.
 */
import React from 'react';
import { Audio, Sequence, staticFile } from 'remotion';
import { Answer } from './gpio-interrupts/Answer';
import { Bounce } from './gpio-interrupts/Bounce';
import { Config } from './gpio-interrupts/Config';
import { Demo } from './gpio-interrupts/Demo';
import { Handler } from './gpio-interrupts/Handler';
import { Isr } from './gpio-interrupts/Isr';
import { Payoff } from './gpio-interrupts/Payoff';
import { Problem } from './gpio-interrupts/Problem';
import { Queue } from './gpio-interrupts/Queue';
import { Service } from './gpio-interrupts/Service';
import { FPS, IRQ_FRAMES, sceneDur, SCENES, SceneId, sceneStart } from './gpio-interrupts/timeline';
import { Types } from './gpio-interrupts/Types';
import { UnderTheHood } from './gpio-interrupts/UnderTheHood';

export { IRQ_FRAMES };

const frames = (id: SceneId) => Math.round(sceneDur(id) * FPS);

const SCENE_COMPONENTS: Record<SceneId, React.FC> = {
  problem: Problem,
  answer: Answer,
  config: Config,
  service: Service,
  handler: Handler,
  isr: Isr,
  queue: Queue,
  demo: Demo,
  bounce: Bounce,
  types: Types,
  idf: UnderTheHood,
  payoff: Payoff,
};

export const GPIOInterrupts: React.FC = () => (
  <>
    {/* generated by scripts/gpio-interrupts-audio.ts from the same timeline */}
    <Audio src={staticFile('gpio-interrupts/mix.wav')} />
    {SCENES.map(({ id }) => {
      const C = SCENE_COMPONENTS[id];
      return (
        <Sequence key={id} from={Math.round(sceneStart(id) * FPS)} durationInFrames={frames(id)} name={id}>
          <C />
        </Sequence>
      );
    })}
  </>
);
