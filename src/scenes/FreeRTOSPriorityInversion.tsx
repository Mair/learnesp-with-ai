/**
 * FreeRTOS priority inversion — when a low task holding a lock is pushed aside by a medium
 * one, the high task waiting for that lock waits for the medium one. A mutex fixes it by
 * lending the waiter's priority to the holder (priority inheritance).
 *
 * Pure ESP-IDF (xSemaphoreCreateMutex / Take / Give, xTaskCreatePinnedToCore, uxTaskPriorityGet,
 * vTaskDelay). Every log line is real output from QEMU (./freertos-priority-inversion/lab).
 *
 *   1 want      high (3) and low (1) share a buffer behind a lock; medium (2) crunches; core 0
 *   2 flag      try 1, a flag (real): high waits 1019 ms behind medium → PRIORITY INVERSION
 *   3 mutex     try 2, the mutex (real): 28 ms; low runs at 3 → PRIORITY INHERITANCE
 *   4 code      the whole program; nothing extra for inheritance
 *   5 inherit   the two rules; uxTaskPriorityGet(NULL) shows it; only a mutex does it
 *   6 trap      sleeping while holding it (real, 470 ms); keep the locked part short (0 ms)
 *   7 payoff    "…that's priority inheritance." Next: semaphores
 *
 * Everything — picture AND soundtrack — is driven by ./freertos-priority-inversion/timeline.ts.
 */
import React from 'react';
import { Audio, Sequence, staticFile } from 'remotion';
import { Code } from './freertos-priority-inversion/Code';
import { Flag } from './freertos-priority-inversion/Flag';
import { Inherit } from './freertos-priority-inversion/Inherit';
import { Mutex } from './freertos-priority-inversion/Mutex';
import { Payoff } from './freertos-priority-inversion/Payoff';
import { Trap } from './freertos-priority-inversion/Trap';
import { Want } from './freertos-priority-inversion/Want';
import { FPS, INVERSION_FRAMES, sceneDur, SCENES, SceneId, sceneStart } from './freertos-priority-inversion/timeline';

export { INVERSION_FRAMES };

const SCENE_COMPONENTS: Record<SceneId, React.FC> = { want: Want, flag: Flag, mutex: Mutex, code: Code, inherit: Inherit, trap: Trap, payoff: Payoff };

export const FreeRTOSPriorityInversion: React.FC = () => (
  <>
    {/* generated by scripts/freertos-priority-inversion-audio.ts from the same timeline */}
    <Audio src={staticFile('freertos-priority-inversion/mix.wav')} />
    {SCENES.map(({ id }) => {
      const C = SCENE_COMPONENTS[id];
      return (
        <Sequence key={id} from={Math.round(sceneStart(id) * FPS)} durationInFrames={Math.round(sceneDur(id) * FPS)} name={id}>
          <C />
        </Sequence>
      );
    })}
  </>
);
