/**
 * FreeRTOS mutexes — one key for a shared thing.
 *
 * Pure ESP-IDF (xSemaphoreCreateMutex, xSemaphoreTake, xSemaphoreGive; the workers pinned with
 * xTaskCreatePinnedToCore). Every log line is real output from QEMU (./freertos-mutexes/lab).
 *
 *   1 want      let's say you want two tasks (one per core) to add to one total → 2,000,000
 *   2 race      try 1, just total++ (real): 1,455,343; read, add, write; both read 41
 *   3 mutex     try 2, a key (real): exactly 2,000,000 → MUTEX; the catch: it costs time
 *   4 code      one function, two tasks, two cursors; create first
 *   5 create    xSemaphoreCreateMutex()
 *   6 take      xSemaphoreTake(total_lock, portMAX_DELAY)
 *   7 give      xSemaphoreGive(total_lock)
 *   8 short     count in mine, lock once
 *   9 trap      a break while holding the key → a silent hang; give before every way out
 *  10 payoff    "That's a mutex."
 *
 * Everything — picture AND soundtrack — is driven by ./freertos-mutexes/timeline.ts.
 */
import React from 'react';
import { Audio, Sequence, staticFile } from 'remotion';
import { Code } from './freertos-mutexes/Code';
import { Create } from './freertos-mutexes/Create';
import { Give } from './freertos-mutexes/Give';
import { Mutex } from './freertos-mutexes/Mutex';
import { Payoff } from './freertos-mutexes/Payoff';
import { Race } from './freertos-mutexes/Race';
import { Short } from './freertos-mutexes/Short';
import { Take } from './freertos-mutexes/Take';
import { Trap } from './freertos-mutexes/Trap';
import { Want } from './freertos-mutexes/Want';
import { FPS, MUTEXES_FRAMES, sceneDur, SCENES, SceneId, sceneStart } from './freertos-mutexes/timeline';

export { MUTEXES_FRAMES };

const SCENE_COMPONENTS: Record<SceneId, React.FC> = { want: Want, race: Race, mutex: Mutex, code: Code, create: Create, take: Take, give: Give, short: Short, trap: Trap, payoff: Payoff };

export const FreeRTOSMutexes: React.FC = () => (
  <>
    {/* generated by scripts/freertos-mutexes-audio.ts from the same timeline */}
    <Audio src={staticFile('freertos-mutexes/mix.wav')} />
    {SCENES.map(({ id }) => {
      const C = SCENE_COMPONENTS[id];
      return (
        <Sequence key={id} from={Math.round(sceneStart(id) * FPS)} durationInFrames={Math.round(sceneDur(id) * FPS)} name={id}>
          <C />
        </Sequence>
      );
    })}
  </>
);
