/**
 * FreeRTOS scheduler & priorities — the highest-priority ready task runs.
 *
 * Pure ESP-IDF (xTaskCreate, vTaskDelay, vTaskPrioritySet, uxTaskPriorityGet,
 * esp_timer_get_time; GPIO calls from Basic GPIO only).
 *
 *   1 problem   two workers at 6 → the fast LED stumbles
 *   2 rule      of the ready tasks, the highest priority runs → PRIORITY
 *   3 states    Blocked · Ready · Running; two cores
 *   4 cases     highest first · a higher one takes a core · lower waits · equal take turns → the LED
 *   5 fix       6 → 4; priority = how soon; busy loop vs vTaskDelay; stay low
 *   6 prio      button task; handles; vTaskPrioritySet / uxTaskPriorityGet
 *   7 demo      the button flips 4 ↔ 6, live
 *   8 trap      a task that never waits → idle starves → task watchdog
 *   9 payoff    "The highest-priority ready task runs. That's the scheduler."
 *
 * Everything — picture AND soundtrack — is driven by ./freertos-scheduler/timeline.ts.
 */
import React from 'react';
import { Audio, Sequence, staticFile } from 'remotion';
import { Cases } from './freertos-scheduler/Cases';
import { Demo } from './freertos-scheduler/Demo';
import { Fix } from './freertos-scheduler/Fix';
import { Payoff } from './freertos-scheduler/Payoff';
import { Prio } from './freertos-scheduler/Prio';
import { Problem } from './freertos-scheduler/Problem';
import { Rule } from './freertos-scheduler/Rule';
import { States } from './freertos-scheduler/States';
import { Trap } from './freertos-scheduler/Trap';
import { FPS, SCHED_FRAMES, sceneDur, SCENES, SceneId, sceneStart } from './freertos-scheduler/timeline';

export { SCHED_FRAMES };

const frames = (id: SceneId) => Math.round(sceneDur(id) * FPS);

const SCENE_COMPONENTS: Record<SceneId, React.FC> = {
  problem: Problem,
  rule: Rule,
  states: States,
  cases: Cases,
  fix: Fix,
  prio: Prio,
  demo: Demo,
  trap: Trap,
  payoff: Payoff,
};

export const FreeRTOSScheduler: React.FC = () => (
  <>
    {/* generated by scripts/freertos-scheduler-audio.ts from the same timeline */}
    <Audio src={staticFile('freertos-scheduler/mix.wav')} />
    {SCENES.map(({ id }) => {
      const C = SCENE_COMPONENTS[id];
      return (
        <Sequence key={id} from={Math.round(sceneStart(id) * FPS)} durationInFrames={frames(id)} name={id}>
          <C />
        </Sequence>
      );
    })}
  </>
);
