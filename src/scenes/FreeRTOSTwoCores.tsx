/**
 * FreeRTOS two cores — pin a task to a core, or let FreeRTOS choose.
 *
 * Pure ESP-IDF (xTaskCreatePinnedToCore, tskNO_AFFINITY, esp_cpu_get_core_id,
 * pcTaskGetName; GPIO output only).
 *
 *   1 problem   workers at 6 take both cores → the LED stumbles; xTaskCreate = either core
 *   2 answer    pin the workers to core 1 → hero PIN
 *   3 home      core 0: app_main, Wi-Fi, Bluetooth → core 1 for your heavy work
 *   4 pin       xTaskCreatePinnedToCore: the same six + the core (0 / 1 / tskNO_AFFINITY)
 *   5 which     esp_cpu_get_core_id(): pinned → always core 1
 *   6 demo      workers on core 1, still 6: both LEDs on the beat
 *   7 price     they share core 1 (½ each), core 0 empty; pin only with a reason
 *   8 payoff    "That's how you use both cores."
 *
 * Everything — picture AND soundtrack — is driven by ./freertos-two-cores/timeline.ts.
 */
import React from 'react';
import { Audio, Sequence, staticFile } from 'remotion';
import { Answer } from './freertos-two-cores/Answer';
import { Demo } from './freertos-two-cores/Demo';
import { Home } from './freertos-two-cores/Home';
import { Payoff } from './freertos-two-cores/Payoff';
import { Pin } from './freertos-two-cores/Pin';
import { Price } from './freertos-two-cores/Price';
import { Problem } from './freertos-two-cores/Problem';
import { Which } from './freertos-two-cores/Which';
import { CORES_FRAMES, FPS, sceneDur, SCENES, SceneId, sceneStart } from './freertos-two-cores/timeline';

export { CORES_FRAMES };

const SCENE_COMPONENTS: Record<SceneId, React.FC> = { problem: Problem, answer: Answer, home: Home, pin: Pin, which: Which, demo: Demo, price: Price, payoff: Payoff };

export const FreeRTOSTwoCores: React.FC = () => (
  <>
    {/* generated by scripts/freertos-two-cores-audio.ts from the same timeline */}
    <Audio src={staticFile('freertos-two-cores/mix.wav')} />
    {SCENES.map(({ id }) => {
      const C = SCENE_COMPONENTS[id];
      return (
        <Sequence key={id} from={Math.round(sceneStart(id) * FPS)} durationInFrames={Math.round(sceneDur(id) * FPS)} name={id}>
          <C />
        </Sequence>
      );
    })}
  </>
);
