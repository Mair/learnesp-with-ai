/**
 * GPIO — switching a pin on and off.
 *
 * Pure ESP-IDF (app_main, driver/gpio.h, vTaskDelay) — no Arduino.
 *
 *   1 problem    gpio_set_level returns ESP_OK, the LED stays dark: every pin starts as a listener
 *   2 answer     make it an output, set its level → G·P·I·O
 *   3 circuit    WROOM pin 24 → 220 Ω → LED → GND, real parts then schematic; Ohm's law; which pins; strapping
 *   4 reset      gpio_reset_pin: pin number vs GPIO number (WROOM-32E pinout); a known state
 *   5 direction  gpio_set_direction: the output driver, OUTPUT is output-only, GPIO 34 → ESP_ERR_INVALID_ARG, level first
 *   6 write      gpio_set_level: 1/0 → 3.3 V / 0 V, the guaranteed bands, any non-zero = high, returns ESP_OK
 *   7 blink      the whole app_main, real time
 *   8 delay      vTaskDelay(pdMS_TO_TICKS(500)): 50 ticks of 10 ms, rounding down, blocked = CPU free, watchdog, dimmer
 *   9 current    knob 2: the resistor sets the current; a pin is a signal, not a supply
 *  10 payoff     "Make it an output. Set its level. That's GPIO."
 *
 * Everything — picture AND soundtrack — is driven by ./gpio/timeline.ts.
 * Edit that, then `npm run gpio`.
 */
import React from 'react';
import { Audio, Sequence, staticFile } from 'remotion';
import { Answer } from './gpio/Answer';
import { Blink } from './gpio/Blink';
import { Circuit } from './gpio/Circuit';
import { Current } from './gpio/Current';
import { Delay } from './gpio/Delay';
import { Payoff } from './gpio/Payoff';
import { Direction } from './gpio/Direction';
import { Problem } from './gpio/Problem';
import { Reset } from './gpio/Reset';
import { FPS, GPIO_FRAMES, sceneDur, SCENES, SceneId, sceneStart } from './gpio/timeline';
import { Write } from './gpio/Write';

export { GPIO_FRAMES };

const frames = (id: SceneId) => Math.round(sceneDur(id) * FPS);

const SCENE_COMPONENTS: Record<SceneId, React.FC> = {
  problem: Problem,
  answer: Answer,
  circuit: Circuit,
  reset: Reset,
  direction: Direction,
  write: Write,
  blink: Blink,
  delay: Delay,
  current: Current,
  payoff: Payoff,
};

export const GPIO: React.FC = () => (
  <>
    {/* generated by scripts/gpio-audio.ts from the same timeline */}
    <Audio src={staticFile('gpio/mix.wav')} />
    {SCENES.map(({ id }) => {
      const C = SCENE_COMPONENTS[id];
      return (
        <Sequence key={id} from={Math.round(sceneStart(id) * FPS)} durationInFrames={frames(id)} name={id}>
          <C />
        </Sequence>
      );
    })}
  </>
);
